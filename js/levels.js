// junta os segmentos em linhas únicas e aponta erros de largura
function buildLevelRows(def) {
  const rows = new Array(14).fill('');
  def.segs.forEach((seg, si) => {
    if (seg.length !== 14) console.warn('Fase', def.id, 'segmento', si, 'tem', seg.length, 'linhas');
    const w = seg[0].length;
    for (let y = 0; y < 14; y++) {
      let r = seg[y] || '';
      if (r.length !== w) { console.warn('Fase', def.id, 'segmento', si, 'linha', y, 'largura', r.length, '≠', w); r = r.padEnd(w, '.').slice(0, w); }
      rows[y] += r;
    }
  });
  return rows;
}
